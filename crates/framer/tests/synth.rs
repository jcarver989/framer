use framer::github::{Ci, Job, Step};
use framer::rust::{CargoWorkspace, Edition, Lints, Profile, Toolchain};
use framer::testing::{render, render_into};
use framer::{
    ChangeKind, DiskFs, FileSystem, MemoryFs, Mode, Preset, Project, SampleFile, TextBlock,
    TextFile, eject,
};
use indoc::indoc;
use std::path::Path;
use tempfile::TempDir;

const HEADER: &str = "# Generated by framer. Do not edit by hand: change .framer/src/main.rs and run `cargo framer`.\n";

/// The kind of preset a team would publish: a few components with options.
struct TeamRust {
    msrv: &'static str,
}

impl TeamRust {
    fn new() -> Self {
        Self { msrv: "1.98" }
    }
}

impl Preset for TeamRust {
    fn apply(self, project: &mut Project) {
        project.add(Toolchain::pinned(format!("{}.0", self.msrv)).components(["clippy"]));
        project.add(
            CargoWorkspace::new()
                .edition(Edition::E2024)
                .rust_version(self.msrv)
                .lints(Lints::clippy_pedantic().allow_clippy(["missing_errors_doc"])),
        );
        project.add(Ci::new().job(Job::fmt()).job(Job::clippy()));
        project.add(TextBlock::new(
            "AGENTS.md",
            "team/conventions",
            "## Conventions\n\nUse real objects in tests.\n",
        ));
    }
}

fn team_project() -> Project {
    let mut project = Project::new();
    project.apply(TeamRust::new());
    project
}

fn is_readonly(fs: &MemoryFs, path: &str) -> bool {
    fs.is_readonly(Path::new(path)).unwrap()
}

#[test]
fn generates_managed_files_with_a_header_and_makes_them_readonly() {
    let fs = render(&team_project()).unwrap();

    assert_eq!(
        fs.get("rust-toolchain.toml").unwrap(),
        format!(
            "{HEADER}[toolchain]\nchannel = \"1.98.0\"\ncomponents = [\"clippy\"]\nprofile = \"minimal\"\n"
        )
    );
    assert!(is_readonly(&fs, "rust-toolchain.toml"));
    assert!(is_readonly(&fs, ".github/workflows/ci.yml"));
    assert!(!is_readonly(&fs, "Cargo.toml"));
    assert!(!is_readonly(&fs, "AGENTS.md"));
    assert_eq!(
        fs.get(".gitignore").unwrap(),
        indoc! {"
        # framer:begin framer
        /.framer/target/
        # framer:end framer
    "}
    );
}

#[test]
fn a_second_run_changes_nothing() {
    let project = team_project();
    let mut fs = render(&project).unwrap();

    let report = project.synth_with(&mut fs, Mode::Write).unwrap();

    assert!(report.is_clean(), "{report}\n{}", report.diff());
}

#[test]
fn keeps_the_parts_of_partly_generated_files_it_does_not_own() {
    let existing = MemoryFs::new()
        .with_file(
            "Cargo.toml",
            indoc! {r#"
                [workspace]
                members = ["old/*"]

                [workspace.dependencies]
                serde = "1"
            "#},
        )
        .with_file("AGENTS.md", "# My repo\n\nRepo-specific notes.\n");

    let fs = render_into(&team_project(), existing).unwrap();

    assert_eq!(
        fs.get("Cargo.toml").unwrap(),
        indoc! {r#"
            [workspace]
            members = ["crates/*"]
            resolver = "3"

            [workspace.dependencies]
            serde = "1"

            [workspace.package]
            edition = "2024"
            rust-version = "1.98"

            [workspace.lints.clippy]
            all = { level = "warn", priority = -1 }
            pedantic = { level = "warn", priority = -1 }
            missing_errors_doc = "allow"
        "#}
    );
    assert_eq!(
        fs.get("AGENTS.md").unwrap(),
        indoc! {"
            # My repo

            Repo-specific notes.

            <!-- framer:begin team/conventions -->
            ## Conventions

            Use real objects in tests.
            <!-- framer:end team/conventions -->
        "}
    );
}

#[test]
fn check_mode_reports_hand_edits_without_writing() {
    let project = team_project();
    let mut fs = render(&project).unwrap();
    fs.set_readonly(Path::new("rust-toolchain.toml"), false)
        .unwrap();
    fs.write(Path::new("rust-toolchain.toml"), "edited\n")
        .unwrap();

    let report = project.synth_with(&mut fs, Mode::Check).unwrap();

    assert_eq!(report.changes.len(), 1);
    assert_eq!(report.changes[0].path, Path::new("rust-toolchain.toml"));
    assert_eq!(report.changes[0].kind, ChangeKind::Updated);
    assert!(report.diff().contains("-edited\n+# Generated by framer."));
    assert_eq!(fs.get("rust-toolchain.toml").unwrap(), "edited\n");
}

#[test]
fn cleans_up_what_is_no_longer_generated() {
    let mut fs = render(&team_project()).unwrap();
    let mut smaller = Project::new();
    smaller.add(CargoWorkspace::new());

    let report = smaller.synth_with(&mut fs, Mode::Write).unwrap();

    assert_eq!(fs.get("rust-toolchain.toml"), None);
    assert_eq!(fs.get(".github/workflows/ci.yml"), None);
    assert_eq!(
        fs.get("AGENTS.md"),
        None,
        "a file that only held a block is removed"
    );
    assert_eq!(
        fs.get("Cargo.toml").unwrap(),
        "[workspace]\nresolver = \"3\"\nmembers = [\"crates/*\"]\n"
    );
    let deleted: Vec<_> = report
        .changes
        .iter()
        .filter(|change| change.kind == ChangeKind::Deleted)
        .map(|change| change.path.display().to_string())
        .collect();
    assert_eq!(
        deleted,
        [
            ".github/workflows/ci.yml",
            "AGENTS.md",
            "rust-toolchain.toml"
        ]
    );
}

#[test]
fn unmanaging_a_file_hands_it_over_to_the_user() {
    let mut fs = render(&team_project()).unwrap();
    let mut project = team_project();
    project
        .unmanage("rust-toolchain.toml")
        .unmanage("AGENTS.md");

    let report = project.synth_with(&mut fs, Mode::Write).unwrap();

    assert!(
        !fs.get("rust-toolchain.toml")
            .unwrap()
            .contains("Generated by framer")
    );
    assert!(!is_readonly(&fs, "rust-toolchain.toml"));
    assert_eq!(
        fs.get("AGENTS.md").unwrap(),
        "## Conventions\n\nUse real objects in tests.\n"
    );
    assert!(
        report
            .changes
            .iter()
            .any(|change| change.kind == ChangeKind::Released)
    );
    assert!(project.synth_with(&mut fs, Mode::Check).unwrap().is_clean());
}

#[test]
fn sample_files_are_written_once() {
    let mut project = Project::new();
    project.add(SampleFile::new("src/main.rs", "fn main() {}\n"));
    let mut fs = render(&project).unwrap();
    fs.write(Path::new("src/main.rs"), "fn main() { todo!() }\n")
        .unwrap();

    let report = project.synth_with(&mut fs, Mode::Write).unwrap();

    assert!(report.is_clean());
    assert_eq!(fs.get("src/main.rs").unwrap(), "fn main() { todo!() }\n");
}

#[test]
fn projects_can_change_what_a_preset_set_up() {
    let mut project = team_project();
    project
        .get_mut::<Ci>()
        .unwrap()
        .job_mut("clippy")
        .unwrap()
        .steps_mut()
        .push(Step::run("cargo deny check"));
    let workspace = project.get_mut::<CargoWorkspace>().unwrap();
    *workspace = workspace
        .clone()
        .profile(Profile::new("dist").inherits("release"));
    project
        .toml("Cargo.toml")
        .set("profile.dist.codegen-units", 1_i64)
        .set("workspace.package.publish", false);
    project
        .toml("rust-toolchain.toml")
        .set("toolchain.profile", "default");

    let fs = render(&project).unwrap();

    assert!(
        fs.get(".github/workflows/ci.yml")
            .unwrap()
            .contains("run: cargo deny check")
    );
    let cargo = fs.get("Cargo.toml").unwrap();
    assert!(cargo.contains("[profile.dist]\ninherits = \"release\"\ncodegen-units = 1\n"));
    assert!(cargo.contains("rust-version = \"1.98\"\npublish = false\n"));
    assert!(
        fs.get("rust-toolchain.toml")
            .unwrap()
            .contains("profile = \"default\"")
    );
}

#[test]
fn overrides_outside_owned_keys_are_owned_too() {
    let mut project = Project::new();
    project
        .toml("Cargo.toml")
        .set("workspace.metadata.team", "core");
    let mut fs = render(&project).unwrap();
    assert!(fs.get("Cargo.toml").unwrap().contains("team = \"core\""));

    Project::new().synth_with(&mut fs, Mode::Write).unwrap();

    assert_eq!(fs.get("Cargo.toml"), None);
}

#[test]
fn two_components_cannot_own_the_same_file() {
    let mut project = Project::new();
    project.add(TextFile::new("README.md", "a"));
    project.add(TextBlock::new("README.md", "b", "b"));

    let error = render(&project).unwrap_err();

    assert_eq!(
        error.to_string(),
        "README.md: cannot generate block `b`: already generated as a generated file"
    );
}

#[test]
fn eject_leaves_ordinary_files_behind() {
    let mut fs = render(&team_project()).unwrap();

    eject(&mut fs).unwrap();

    assert!(
        !fs.get("rust-toolchain.toml")
            .unwrap()
            .contains("Generated by framer")
    );
    assert!(!is_readonly(&fs, "rust-toolchain.toml"));
    assert!(!fs.get("AGENTS.md").unwrap().contains("framer:begin"));
    assert_eq!(fs.get(".framer/manifest.json"), None);
}

#[test]
fn ci_workflow_output() {
    let mut project = Project::new();
    project.add(
        Ci::new()
            .matrix(["ubuntu-latest", "macos-latest"])
            .job(Job::clippy())
            .job(Job::test()),
    );

    let fs = render(&project).unwrap();

    let expected = indoc! {r#"
        name: CI
        on:
          pull_request:
          push:
            branches: [main]
        env:
          CARGO_INCREMENTAL: "0"
        permissions:
          contents: read
        jobs:
          clippy:
            name: Clippy
            runs-on: ubuntu-latest
            timeout-minutes: 30
            steps:
              - name: Checkout
                uses: actions/checkout@v6
              - name: Install Rust
                uses: actions-rust-lang/setup-rust-toolchain@v1
              - name: Run Clippy
                run: cargo clippy --workspace --all-targets --all-features -- -D warnings
          test:
            name: Test
            strategy:
              fail-fast: false
              matrix:
                os: [ubuntu-latest, macos-latest]
            runs-on: ${{ matrix.os }}
            timeout-minutes: 30
            steps:
              - name: Checkout
                uses: actions/checkout@v6
              - name: Install Rust
                uses: actions-rust-lang/setup-rust-toolchain@v1
              - name: Run tests
                run: cargo test --workspace --all-features
          framer:
            name: Generated files
            runs-on: ubuntu-latest
            timeout-minutes: 15
            steps:
              - name: Checkout
                uses: actions/checkout@v6
              - name: Install Rust
                uses: actions-rust-lang/setup-rust-toolchain@v1
              - name: Check generated files are up to date
                run: cargo run --locked --manifest-path .framer/Cargo.toml -- --check
    "#};
    assert_eq!(
        fs.get(".github/workflows/ci.yml").unwrap(),
        format!("{HEADER}{expected}")
    );
}

#[test]
fn works_against_a_real_repository() {
    let dir = TempDir::new().unwrap();
    let project = team_project();
    let mut fs = DiskFs::new(dir.path());

    project.synth_with(&mut fs, Mode::Write).unwrap();
    let report = project.synth_with(&mut fs, Mode::Write).unwrap();

    assert!(report.is_clean());
    assert!(
        fs.is_readonly(Path::new(".github/workflows/ci.yml"))
            .unwrap()
    );
    assert!(dir.path().join(".framer/manifest.json").is_file());

    let mut smaller = Project::new();
    smaller.add(CargoWorkspace::new());
    smaller.synth_with(&mut fs, Mode::Write).unwrap();

    assert!(!dir.path().join(".github/workflows/ci.yml").exists());
}
