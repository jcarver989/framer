use std::ffi::OsStr;
use std::path::Path;

/// How a file writes line comments, which decides how framer marks the parts
/// of it that it generates.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CommentStyle {
    /// `# comment`: TOML, YAML, shell scripts, `.gitignore`, justfiles.
    Hash,
    /// `// comment`: Rust, JavaScript, Go.
    Slash,
    /// `<!-- comment -->`: Markdown, HTML.
    Html,
    /// Formats without comments, such as JSON.
    None,
}

const HASH_NAMES: &[&str] = &[
    ".dockerignore",
    ".editorconfig",
    ".gitattributes",
    ".gitignore",
    ".tool-versions",
    "Dockerfile",
    "Justfile",
    "Makefile",
    "justfile",
];
const HASH_EXTENSIONS: &[&str] = &[
    "bash", "cfg", "conf", "py", "rb", "sh", "toml", "yaml", "yml",
];
const SLASH_EXTENSIONS: &[&str] = &[
    "c", "cc", "cpp", "go", "h", "java", "js", "jsx", "kt", "mjs", "proto", "rs", "swift", "ts",
    "tsx",
];
const HTML_EXTENSIONS: &[&str] = &["htm", "html", "markdown", "md", "svg", "xml"];

impl CommentStyle {
    pub fn for_path(path: &Path) -> Self {
        let name = path.file_name().and_then(OsStr::to_str).unwrap_or_default();
        if HASH_NAMES.contains(&name) {
            return Self::Hash;
        }
        let extension = path.extension().and_then(OsStr::to_str).unwrap_or_default();
        if HASH_EXTENSIONS.contains(&extension) {
            Self::Hash
        } else if SLASH_EXTENSIONS.contains(&extension) {
            Self::Slash
        } else if HTML_EXTENSIONS.contains(&extension) {
            Self::Html
        } else {
            Self::None
        }
    }

    /// `text` as a single-line comment, or `None` when the format has no comments.
    pub fn comment(self, text: &str) -> Option<String> {
        match self {
            Self::Hash => Some(format!("# {text}")),
            Self::Slash => Some(format!("// {text}")),
            Self::Html => Some(format!("<!-- {text} -->")),
            Self::None => None,
        }
    }
}

const HEADER: &str =
    "Generated by framer. Do not edit by hand: change .framer/src/main.rs and run `cargo framer`.";

pub(crate) fn add_header(path: &Path, contents: &str) -> String {
    match CommentStyle::for_path(path).comment(HEADER) {
        Some(header) => format!("{header}\n{contents}"),
        None => contents.to_owned(),
    }
}

pub(crate) fn strip_header(path: &Path, contents: &str) -> String {
    let Some(header) = CommentStyle::for_path(path).comment(HEADER) else {
        return contents.to_owned();
    };
    match contents.strip_prefix(&header) {
        Some("") => String::new(),
        Some(rest) if rest.starts_with('\n') => rest[1..].to_owned(),
        _ => contents.to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn picks_comment_style_from_name_then_extension() {
        assert_eq!(
            CommentStyle::for_path(Path::new(".gitignore")),
            CommentStyle::Hash
        );
        assert_eq!(
            CommentStyle::for_path(Path::new("a/Cargo.toml")),
            CommentStyle::Hash
        );
        assert_eq!(
            CommentStyle::for_path(Path::new("AGENTS.md")),
            CommentStyle::Html
        );
        assert_eq!(
            CommentStyle::for_path(Path::new("src/lib.rs")),
            CommentStyle::Slash
        );
        assert_eq!(
            CommentStyle::for_path(Path::new("package.json")),
            CommentStyle::None
        );
    }

    #[test]
    fn header_round_trips() {
        let path = Path::new("rust-toolchain.toml");
        let generated = add_header(path, "[toolchain]\n");

        assert!(generated.starts_with("# Generated by framer."));
        assert_eq!(strip_header(path, &generated), "[toolchain]\n");
    }

    #[test]
    fn strip_header_leaves_other_files_alone() {
        let path = Path::new("README.md");

        assert_eq!(strip_header(path, "# Title\n"), "# Title\n");
        assert_eq!(add_header(Path::new("a.json"), "{}"), "{}");
    }
}
